"""Remote preparation (task 12): pinned downloads, checkpoint conversion, scalers, and a
replay of dataset actions through the exact TwoRoom check.

Public Hub repositories only, so no credential is needed or sent to the rental. Every
artifact is verified by size and sha256 against configs/tworoom12/design.json before use.
The replay is a diagnostic: it shows whether the dataset the world model learned from was
generated by the same dynamics the exact check encodes.
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments"))
os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")
from helpers.dsrl06_infra import atomic_json, utc
from helpers.tworoom12_protocol import design, digest

DATA = ROOT / "data/tworoom12"
OUT = ROOT / "outputs/tworoom12"
os.environ.setdefault("STABLEWM_HOME", str(DATA / "stablewm"))


def remap_vit_keys(sd):
    """Map pre-transformers-v5 ViT keys to the current vit_hf layout."""
    out = {}
    for key, value in sd.items():
        nk = key.replace("encoder.encoder.layer.", "encoder.layers.")
        nk = nk.replace("attention.attention.query", "attention.q_proj")
        nk = nk.replace("attention.attention.key", "attention.k_proj")
        nk = nk.replace("attention.attention.value", "attention.v_proj")
        nk = nk.replace("attention.output.dense", "attention.o_proj")
        nk = nk.replace("intermediate.dense", "mlp.fc1")
        nk = nk.replace(".output.dense", ".mlp.fc2")
        out[nk] = value
    return out


def verify(path, expected_sha, expected_bytes):
    path = Path(path)
    if path.stat().st_size != expected_bytes:
        raise ValueError(f"Size mismatch for {path.name}")
    if digest(path) != expected_sha:
        raise ValueError(f"Hash mismatch for {path.name}")


def fetch_model(spec):
    from huggingface_hub import hf_hub_download

    pins = spec["pins"]
    folder = DATA / "hf_tworoom"
    folder.mkdir(parents=True, exist_ok=True)
    for name in ("config.json", "weights.pt"):
        if not (folder / name).exists():
            hf_hub_download(
                pins["model_repo"],
                name,
                repo_type="model",
                revision=pins["model_revision"],
                local_dir=str(folder),
            )
    verify(folder / "weights.pt", pins["model_weights_sha256"], pins["model_weights_bytes"])
    return folder


def convert(folder, spec):
    import torch
    from hydra.utils import instantiate

    name = spec["pins"]["checkpoint_name"]
    target = Path(os.environ["STABLEWM_HOME"]) / f"checkpoints/{name}_object.ckpt"
    if target.exists():
        return target
    cfg = json.loads((folder / "config.json").read_text())
    model = instantiate(cfg)
    sd = torch.load(folder / "weights.pt", map_location="cpu", weights_only=False)
    try:
        model.load_state_dict(remap_vit_keys(sd), strict=True)
        remapped = True
    except RuntimeError:
        model.load_state_dict(sd, strict=True)
        remapped = False
    target.parent.mkdir(parents=True, exist_ok=True)
    torch.save(model, target)
    atomic_json(
        target.with_suffix(".json"),
        {"utc": utc(), "remapped_keys": remapped, "source_sha256": digest(folder / "weights.pt")},
    )
    return target


def fetch_dataset(spec):
    """Download the pinned archive, verify it, and stream its single HDF5 member out."""
    import tarfile

    import zstandard
    from huggingface_hub import hf_hub_download

    pins = spec["pins"]
    raw = DATA / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    archive = raw / pins["dataset_file"]
    if not archive.exists():
        hf_hub_download(
            pins["dataset_repo"],
            pins["dataset_file"],
            repo_type="dataset",
            revision=pins["dataset_revision"],
            local_dir=str(raw),
        )
    marker = raw / "verified.json"
    if not marker.exists():
        verify(archive, pins["dataset_sha256"], pins["dataset_bytes"])
        atomic_json(marker, {"utc": utc(), "sha256": pins["dataset_sha256"]})
    processed = DATA / "processed" / pins["dataset_member"]
    if not processed.exists():
        processed.parent.mkdir(parents=True, exist_ok=True)
        staging = processed.with_name(processed.name + ".part")
        staging.unlink(missing_ok=True)
        try:
            with archive.open("rb") as fin:
                reader = zstandard.ZstdDecompressor().stream_reader(fin)
                with tarfile.open(fileobj=reader, mode="r|") as tar:
                    for member in tar:
                        if Path(member.name).name != pins["dataset_member"] or not member.isfile():
                            continue
                        source = tar.extractfile(member)
                        with staging.open("wb") as fout:
                            shutil.copyfileobj(source, fout, length=16 << 20)
                        break
            if not staging.exists() or staging.stat().st_size == 0:
                raise ValueError("Dataset member not found in the archive")
        except BaseException:
            staging.unlink(missing_ok=True)
            raise
        staging.rename(processed)
    return processed


def build_scalers(h5_path):
    import h5py
    import hdf5plugin  # noqa: F401
    import numpy as np

    path = DATA / "scalers.json"
    if path.exists():
        return path
    columns = {}
    with h5py.File(h5_path, "r") as f:
        for col in ("action", "proprio"):
            data = np.asarray(f[col][:], dtype=np.float64)
            data = data[~np.isnan(data).any(axis=1)]
            scale = data.std(axis=0)
            scale[scale == 0] = 1.0
            columns[col] = {
                "mean": data.mean(axis=0).tolist(),
                "scale": scale.tolist(),
                "rows": int(len(data)),
            }
        meta = {
            "steps": int(len(f["proprio"])),
            "episodes": int(len(f["ep_len"])),
            "pixels_shape": list(f["pixels"].shape[1:]),
            "door_columns": np.unique(np.asarray(f["observation"][:20000, 4:6]), axis=0).tolist(),
        }
    atomic_json(path, {"utc": utc(), "columns": columns, "dataset": meta})
    return path


def replay_dataset(h5_path, spec, episodes=500):
    """One-step replay of recorded actions through the exact model.

    Row t holds the state before action t, which produces row t + 1. Stored actions are
    rounded to two decimals, so a one-step error up to speed * 0.005 = 0.025 px is rounding,
    not dynamics; larger errors would mean the data came from different dynamics.
    """
    import h5py
    import hdf5plugin  # noqa: F401
    import numpy as np
    import torch

    from helpers.tworoom12_planner import tworoom_path

    geometry = spec["environment"]["geometry"]
    errors = []
    with h5py.File(h5_path, "r") as f:
        offsets = np.asarray(f["ep_offset"][:])
        lengths = np.asarray(f["ep_len"][:])
        pick = np.linspace(0, len(offsets) - 1, episodes).round().astype(int)
        for i in pick:
            lo, n = int(offsets[i]), int(lengths[i])
            pos = np.asarray(f["pos_agent"][lo : lo + n], dtype=np.float64)
            act = np.asarray(f["action"][lo : lo + n], dtype=np.float64)
            for t in range(n - 1):
                step = torch.as_tensor(act[t]).view(1, 1, 1, 2)
                pred = tworoom_path(pos[t], step, geometry)[0, 0, 0].numpy()
                errors.append(float(np.linalg.norm(pred - pos[t + 1])))
    errors = np.asarray(errors)
    return {
        "episodes": int(len(pick)),
        "steps": int(len(errors)),
        "max_px": float(errors.max()),
        "median_px": float(np.median(errors)),
        "p999_px": float(np.percentile(errors, 99.9)),
        "steps_over_0p05_px": int((errors > 0.05).sum()),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify-only", action="store_true")
    args = parser.parse_args()
    spec = design()
    OUT.mkdir(parents=True, exist_ok=True)
    folder = fetch_model(spec)
    checkpoint = convert(folder, spec)
    if args.verify_only:
        print(json.dumps({"checkpoint": str(checkpoint), "verified": True}))
        return
    import torch

    if not torch.cuda.is_available():
        raise RuntimeError("Preparation requires the rental GPU")
    h5_path = fetch_dataset(spec)
    scalers = build_scalers(h5_path)
    replay = replay_dataset(h5_path, spec)
    from helpers.tworoom12_runtime import load_world_model

    model = load_world_model("cuda", spec["pins"]["checkpoint_name"])
    parameters = sum(p.numel() for p in model.parameters())
    free = shutil.disk_usage(ROOT).free
    receipt = {
        "utc": utc(),
        "checkpoint": str(checkpoint),
        "checkpoint_sha256": digest(checkpoint),
        "model_parameters": int(parameters),
        "scalers_sha256": digest(scalers),
        "scalers": json.loads(Path(scalers).read_text()),
        "dataset_replay": replay,
        "free_disk_gb": free / 1e9,
        "gpu": torch.cuda.get_device_name(),
    }
    atomic_json(OUT / "prepare-complete.json", receipt)
    print(json.dumps({"status": "prepared", "dataset_replay": replay}))


if __name__ == "__main__":
    main()
