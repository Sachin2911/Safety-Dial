"""Resumable CMA-ES and random search with matched panels and native references."""

from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import pickle
import shutil

import cma
import numpy as np

from maniguard_adapter import AdapterSpec, FEATURE_NAMES
from maniguard_evolution_episode import BudgetExhausted, atomic_json, utc
from maniguard_evolution_scoring import candidate_score, summarize
from maniguard_evolution_selection import (
    choose_selection, nominate_elite, selection_schedule, task_major_cases,
)
from maniguard_evolution_v3 import mutation_scales


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()


class Search:
    """Canonical state is one atomic checkpoint. JSON exports are for inspection.

    Only restore checkpoints generated by this program in your own run directory.
    Fitness and validation remain descriptive development evidence.
    """

    def __init__(self, config, root, evaluator, *, resume=False):
        self.config, self.root, self.evaluate = config, Path(root), evaluator
        self.spec = AdapterSpec(**config["adapter"])
        self.config_hash = digest(config)
        checkpoint = self.root / "checkpoint.pkl"
        if resume:
            with checkpoint.open("rb") as stream:
                payload = pickle.load(stream)
            if payload["config_hash"] != self.config_hash:
                raise ValueError("Resume configuration differs from the original run")
            self.state, self.es, self.rng = payload["state"], payload["es"], payload["rng"]
            np.random.set_state(payload["numpy_random_state"])
        else:
            if checkpoint.exists():
                raise ValueError("Existing run requires explicit resume")
            self.root.mkdir(parents=True, exist_ok=True)
            self.rng = np.random.default_rng(config["search"]["seed"])
            initial = self.spec.initial_parameters(config["search"]["initialization_seed"])
            warmstart = config["search"].get("initial_controller")
            if warmstart:
                artifact = json.loads(Path(warmstart).read_text())
                if artifact["spec"] != asdict(self.spec):
                    raise ValueError("Warm-start controller has a different specification")
                initial = np.asarray(artifact["parameters"], dtype=float)
                self.spec.unpack(initial)
            self.es = None
            if config["search"]["method"] == "cmaes":
                options = {
                    "popsize": config["search"]["population"],
                    "seed": config["search"]["seed"], "bounds": [-3, 3],
                    "CMA_diagonal": True, "verbose": -9, "verb_log": 0}
                profile = config["search"].get("mutation_profile", "isotropic")
                if profile != "isotropic":
                    options["CMA_stds"] = mutation_scales(
                        self.spec, config["search"]["sigma"], profile).tolist()
                self.es = cma.CMAEvolutionStrategy(initial, config["search"]["sigma"], options)
            elif config["search"]["method"] != "random":
                raise ValueError("Training method must be cmaes or random")
            self.state = {"created_utc": utc(), "status": "ready", "generation": 0,
                          "current": None, "generations": [], "jobs": {},
                          "initial": initial.tolist(), "validation": [], "selected": None,
                          "phase": "training", "selection": None, "selected_kind": None,
                          "final_mean": None}
            atomic_json(self.root / "config.json", config)
            self.save()

    def save(self):
        payload = {"state": self.state, "es": self.es, "rng": self.rng,
                   "config_hash": self.config_hash, "numpy_random_state": np.random.get_state()}
        temporary = self.root / "checkpoint.tmp"
        with temporary.open("wb") as stream:
            pickle.dump(payload, stream, protocol=pickle.HIGHEST_PROTOCOL)
        temporary.replace(self.root / "checkpoint.pkl")
        atomic_json(self.root / "status.json", self.state)

    def artifact(self, parameters, enabled=True):
        self.spec.unpack(parameters)
        artifact = {"schema": "maniguard-recurrent-residual-v1", "spec": asdict(self.spec),
                    "parameters": list(parameters), "enabled": enabled,
                    "feature_names": list(FEATURE_NAMES), "privileged_simulator_inputs": True}
        if self.config["search"]["objective"] == "completion_progress_contact_v3":
            artifact["progress_version"] = 3
        return artifact

    def panel(self, label, parameters, cases, enabled=True):
        rows = []
        artifact = self.artifact(parameters, enabled)
        for task, seed in cases:
            key = f"{label}_t{task}_s{seed}"
            if key not in self.state["jobs"]:
                self.state["active"] = {"label": label, "task": task, "seed": seed}
                self.save()
                row = self.evaluate(label, task, seed, artifact)
                self.state["jobs"][key] = row
                self.state.pop("active", None)
                self.save()
            row = self.state["jobs"][key]
            if not row.get("valid", False):
                raise RuntimeError(f"Invalid episode {key}: {row.get('error', 'unknown error')}")
            rows.append(row)
        return rows

    def snapshot_generation(self, g, mean):
        parent = self.root / "generation-snapshots"
        parent.mkdir(exist_ok=True)
        destination = parent / f"g{g:03d}"
        if destination.exists():
            return
        temporary = parent / f".g{g:03d}.tmp"
        if temporary.exists():
            shutil.rmtree(temporary)
        temporary.mkdir()
        for name in ("checkpoint.pkl", "status.json"):
            shutil.copy2(self.root / name, temporary / name)
        atomic_json(temporary / "controller.json", self.artifact(mean))
        atomic_json(temporary / "generation.json", self.state["generations"][g])
        atomic_json(temporary / "snapshot.json", {
            "captured_utc": utc(), "generation": g,
            "state_generation": self.state["generation"],
            "files": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                      for p in temporary.iterdir() if p.is_file()},
        })
        temporary.rename(destination)

    def select_v3(self):
        if self.state["selection"] is None:
            elite = nominate_elite(self.state["generations"], self.state["initial"])
            self.state["selection"] = {
                "elite_provenance": {k: v for k, v in elite.items() if k != "parameters"},
                "nominations": {"native": self.state["initial"],
                                "elite": elite["parameters"], "mean": self.state["final_mean"]},
                "decision": None,
            }
            self.state["phase"] = "selection"
            self.save()
        selection = self.state["selection"]
        if selection["decision"] is None:
            for task, seed, kinds in selection_schedule(self.config["selection"]):
                for kind in kinds:
                    self.panel("selection_" + kind, selection["nominations"][kind],
                               [(task, seed)], kind != "native")
            rows = {kind: [self.state["jobs"][f"selection_{kind}_t{task}_s{seed}"]
                           for task, seed in task_major_cases(self.config["selection"])]
                    for kind in ("native", "elite", "mean")}
            decision = choose_selection(rows, self.config["search"]["objective"])
            decision["parameters"] = selection["nominations"][decision["winner"]]
            decision["elite_provenance"] = selection["elite_provenance"]
            path = self.root / "selection.json"
            if path.exists():
                old = json.loads(path.read_text())
                if {k: v for k, v in old.items() if k != "frozen_utc"} != decision:
                    raise ValueError("Recovered selection receipt differs from completed panels")
                decision = old
            else:
                decision["frozen_utc"] = utc()
                atomic_json(path, decision)
            selection["decision"] = decision
            selection["receipt_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
            self.state["selected"] = list(decision["parameters"])
            self.state["selected_kind"] = decision["winner"]
            atomic_json(self.root / "controller.json", self.artifact(
                self.state["selected"], decision["winner"] != "native"))
            self.save()
        self.verify_selection()

    def verify_selection(self):
        selection = self.state["selection"]
        path = self.root / "selection.json"
        if hashlib.sha256(path.read_bytes()).hexdigest() != selection["receipt_sha256"]:
            raise ValueError("Frozen selection changed after development selection")
        decision = json.loads(path.read_text())
        if (decision != selection["decision"]
                or decision["parameters"] != self.state["selected"]
                or decision["winner"] != self.state["selected_kind"]):
            raise ValueError("Selected parameters or identity changed after freezing")

    def run(self):
        cfg = self.config["search"]
        self.state["status"] = "running"
        self.save()
        try:
            while self.state["generation"] < cfg["generations"]:
                self.state["phase"] = "training"
                g = self.state["generation"]
                if self.state["current"] is None:
                    if self.es is not None:
                        if cfg.get("native_anchor", False):
                            native_genotype = self.es.gp.geno(
                                np.asarray(self.state["initial"]), copy=True,
                                from_bounds=self.es.boundary_handler.inverse)
                            self.es.inject([native_genotype], force=True)
                        candidates = [np.asarray(x).tolist() for x in self.es.ask()]
                        if cfg.get("native_anchor", False):
                            initial = np.asarray(self.state["initial"])
                            matches = [i for i, theta in enumerate(candidates)
                                       if np.allclose(theta, initial, atol=1e-12, rtol=0)]
                            if len(matches) != 1:
                                raise ValueError("CMA-ES did not return the injected native point")
                            # Genotype/phenotype round trips can add machine roundoff.
                            # Rekey the sent-solution archive while preserving the
                            # original injected genotype used by active-CMA bookkeeping.
                            index = matches[0]
                            if not np.array_equal(candidates[index], initial):
                                entry = self.es.sent_solutions.pop(np.asarray(candidates[index]))
                                self.es.sent_solutions.insert(
                                    initial.copy(), geno=entry["geno"], iteration=entry["iteration"])
                            candidates[index] = initial.tolist()
                    else:
                        scales = mutation_scales(
                            self.spec, cfg["sigma"], cfg.get("mutation_profile", "isotropic"))
                        candidates = np.clip(self.rng.normal(
                            self.state["initial"], cfg["sigma"] * scales,
                            (cfg["population"], self.spec.parameter_count)), -3, 3).tolist()
                        if cfg.get("native_anchor", False):
                            candidates[0] = self.state["initial"].copy()
                    order = self.rng.permutation(cfg["population"]).tolist()
                    self.state["current"] = {"candidates": candidates, "order": order}
                    self.save()
                current = self.state["current"]
                cases = [(task, cfg["policy_seeds"][g]) for task in cfg["tasks"]]
                # Alternate native reference placement to reduce systematic time ordering.
                if g % 2 == 0:
                    self.panel(f"g{g:03d}_native", self.state["initial"], cases, False)
                for i in current["order"]:
                    self.panel(f"g{g:03d}_c{i:03d}", current["candidates"][i], cases)
                native = self.panel(f"g{g:03d}_native", self.state["initial"], cases, False)
                rows = [self.panel(f"g{g:03d}_c{i:03d}", theta, cases)
                        for i, theta in enumerate(current["candidates"])]
                scores = [candidate_score(panel, cfg["objective"]) for panel in rows]
                if self.es is not None:
                    # pycma archives ndarray byte keys differently from Python lists.
                    # Restore arrays after durable JSON-friendly parameter storage.
                    self.es.tell([np.asarray(theta, dtype=float)
                                  for theta in current["candidates"]],
                                 [-score for score in scores])
                record = {"generation": g, "cases": cases, "scores": scores,
                          "native": summarize(native),
                          "candidates": [summarize(panel) for panel in rows],
                          "parameters": current["candidates"], "completed_utc": utc(),
                          "anchor_indices": [i for i, theta in enumerate(current["candidates"])
                                             if np.array_equal(theta, self.state["initial"])]}
                if cfg.get("native_anchor") and len(record["anchor_indices"]) != 1:
                    raise ValueError("Each population must contain exactly one native anchor")
                self.state["generations"].append(record)
                self.state["generation"] += 1
                self.state["current"] = None
                if self.es is not None:
                    selected = np.asarray(self.es.result.xfavorite).tolist()
                else:
                    best = max((score, gidx, i) for gidx, row in
                               enumerate(self.state["generations"])
                               for i, score in enumerate(row["scores"]))
                    selected = self.state["generations"][best[1]]["parameters"][best[2]]
                self.state["final_mean"] = selected
                if "selection" not in self.config:
                    self.state["selected"] = selected
                    atomic_json(self.root / "controller.json", self.artifact(selected))
                else:
                    atomic_json(self.root / "mean-controller.json", self.artifact(selected))
                self.save()
                self.snapshot_generation(g, selected)
                print(json.dumps({"generation": g, "scores": scores,
                                  "native": record["native"]}), flush=True)
            validation = self.config["validation"]
            if "selection" in self.config:
                self.select_v3()
                cases = task_major_cases(validation)
            else:
                cases = [(task, seed) for seed in validation["policy_seeds"]
                         for task in validation["tasks"]]
            self.state["phase"] = "validation"
            self.save()
            # Validation never participates in candidate selection or ES updates.
            for i, case in enumerate(cases):
                arms = ("native", "selected") if i % 2 == 0 else ("selected", "native")
                for arm in arms:
                    if "selection" in self.config:
                        self.verify_selection()
                    parameters = (self.state["initial"] if arm == "native"
                                  else self.state["selected"])
                    enabled = arm != "native" and self.state.get("selected_kind") != "native"
                    self.panel("validation_" + arm, parameters, [case], enabled)
            self.state["validation"] = {
                arm: summarize([row for key, row in self.state["jobs"].items()
                                if key.startswith("validation_" + arm + "_")])
                for arm in ("native", "selected")}
            self.state["status"] = "completed"
            self.state["phase"] = "completed"
        except BudgetExhausted as error:
            self.state.update(status="budget_exhausted", stop_reason=str(error))
        except BaseException as error:
            status = "interrupted" if isinstance(error, KeyboardInterrupt) else "failed"
            self.state.update(status=status,
                              error_type=type(error).__name__, error=str(error)[:800])
            self.save()
            raise
        finally:
            self.state["updated_utc"] = utc()
            self.save()
        return self.state
