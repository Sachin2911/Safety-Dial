"""Analyse the pilot records into PilotResults.md (protocol: SafeBlock/Pilot.md).

    python3 SafeBlock/experiments/pilot_analyse.py

Reads the local mirror of the host records (SafeBlock/outputs/pilot-20261101), writes
SafeBlock/PilotResults.md and SafeBlock/outputs/pilot-20261101/pilot-results.json.
Partial records give a partial report.
"""

import argparse
import json
from pathlib import Path

from stage1_analyse import failure_kind, rows, violated, wilson  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
FEATURES = ["retrieval_distance", "imagined_cost", "mean_arm", "closing_fraction", "progress"]
ARMS = ["native", "untrained", "random", "cma"]
LABEL = {"native": "Native `ap_rank`", "untrained": "Untrained selector", "random": "Random-search nominee", "cma": "CMA-ES nominee"}


def summaries(root, phase):
    out = {}
    if not (root / phase).exists():
        return out
    for job_dir in sorted((root / phase).glob("*")):
        if not job_dir.is_dir():
            continue
        for att in sorted(job_dir.glob("attempt-*")):
            if (att / "summary.json").exists():
                out[job_dir.name] = (att, json.loads((att / "summary.json").read_text()))
                break
    return out


def violation_kind(s, last):
    """Failure kind from the terminal row, for benchmark and post-success violations alike."""
    if s.get("boundary_exit"):
        return "boundary_exit"
    terms = last.get("termination_terms", {})
    if last.get("after", {}).get("top_displaced"):
        kind = "top_displaced"
    elif terms.get("cube_2_dropping"):
        kind = "middle_drop"
    elif terms.get("cube_3_dropping"):
        kind = "top_drop"
    elif terms.get("ee_position"):
        kind = "boundary_exit"
    else:
        kind = "other"
    return ("post-success " if s.get("post_success_violation") and not s.get("violation") else "") + kind


def outcome(att, s):
    kind = s.get("outcome")
    if violated(s):
        try:
            kind = violation_kind(s, rows(att)[-1])
        except Exception:  # noqa: BLE001
            pass
    return {
        "sustained": int(bool(s.get("sustained_safe_success"))),
        "success": int(bool(s.get("safe_success"))),
        "violated": int(violated(s)),
        "controls": s.get("controls") or s.get("steps"),
        "kind": kind,
        "choice_changes": s.get("adapter_choice_changes"),
        "plans": s.get("plans"),
    }


def code(o):
    if o["sustained"]:
        return "S"
    if o["success"] and o["violated"]:
        return "sV"
    if o["success"]:
        return "s"
    if o["violated"]:
        return "V"
    return "."


def fmt(values, nd=2):
    return ", ".join(f"{v:+.{nd}f}" for v in values)


def ci(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} [{lo:.2f}, {hi:.2f}]" if lo is not None else f"{k}/{n}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT / "SafeBlock/outputs/pilot-20261101")
    parser.add_argument("--config", type=Path, default=ROOT / "SafeBlock/configs/pilot-20261101.json")
    parser.add_argument("--output", type=Path, default=ROOT / "SafeBlock/PilotResults.md")
    args = parser.parse_args()
    cfg = json.loads(args.config.read_text())
    root = args.root
    R = {"root": str(root.relative_to(ROOT)) if root.is_relative_to(ROOT) else str(root)}
    md = ["# Pilot results: the TwoRoom adapter recipe on Block Plucking", "",
          f"Records: `{R['root']}`. Protocol: [Pilot.md](Pilot.md), frozen settings `configs/pilot-20261101.json`. "
          "Generated by `experiments/pilot_analyse.py`; partial records give a partial report.", ""]

    # ---------------- Smoke ----------------
    parity_path = root / "smoke" / "parity.json"
    if parity_path.exists():
        parity = json.loads(parity_path.read_text())
        R["smoke"] = parity
        md += ["## Parity smoke", "", f"Passed: **{parity['passed']}**.", "",
               "| seed | controls (reference / ours) | identical actions | identical camera hashes | same outcome | adapter changes |", "|---|---|---:|---:|---|---:|"]
        for p in parity["pairs"]:
            if "error" in p:
                md.append(f"| {p['seed']} | {p['error']} | | | | |")
            else:
                md.append(f"| {p['seed']} | {p['controls_reference']} / {p['controls_ours']} | {p['same_action']} | {p['same_camera']} | {p['same_outcome']} | {p['adapter_changes']} |")
        md.append("")

    # ---------------- CMA trace ----------------
    trace_path = root / "cma" / "trace.json"
    if trace_path.exists():
        trace = json.loads(trace_path.read_text())
        gens = trace["generations"]
        def base_fitness(seed):
            ref = ROOT / "SafeBlock/outputs/stage1-20261102/S1C" / f"S1C-{seed}-bare"
            for att in sorted(ref.glob("attempt-*")):
                if (att / "summary.json").exists():
                    s = json.loads((att / "summary.json").read_text())
                    return cfg["fitness"]["sustained"] * int(bool(s.get("sustained_safe_success"))) + cfg["fitness"]["success"] * int(bool(s.get("safe_success"))) - cfg["fitness"]["violated"] * int(violated(s))
            return None

        for g in gens:
            g["base_fitness"] = [base_fitness(s) for s in g["starts"]]
        R["cma"] = {"generations": len(gens), "trace": [{k: g[k] for k in ("generation", "starts", "fitness", "best", "mean_fitness", "sigma_after", "mean_after", "base_fitness")} for g in gens]}
        md += ["## CMA-ES training trace", "",
               f"{len(gens)} of {cfg['cma']['generations']} generations. Fitness per candidate = sum over its two starts of "
               f"{cfg['fitness']['sustained']} sustained + {cfg['fitness']['success']} success - {cfg['fitness']['violated']} violated (range -2 to 180). "
               "Starts: one where the base violated, one where it did not.", "",
               "| gen | starts | base on these starts | candidate fitness | best | mean | sigma after | mean weights after (" + ", ".join(FEATURES) + ") |",
               "|---:|---|---:|---|---:|---:|---:|---|"]
        for g in gens:
            base = sum(b for b in g["base_fitness"] if b is not None)
            md.append(f"| {g['generation']} | {g['starts'][0]}, {g['starts'][1]} | {base:.0f} | {', '.join(f'{v:.0f}' for v in g['fitness'])} | {g['best']:.0f} | {g['mean_fitness']:.1f} | {g['sigma_after']:.3f} | {fmt(g['mean_after'])} |")
        missing = sum(e["missing"] for g in gens for parts in g["episodes"] for e in parts)
        sustained = sum(e["sustained"] for g in gens for parts in g["episodes"] for e in parts)
        viol = sum(e["violated"] for g in gens for parts in g["episodes"] for e in parts)
        n = sum(len(parts) for g in gens for parts in g["episodes"])
        md += ["", f"Training episodes {n}: sustained {sustained}, violated {viol}, missing {missing}.", ""]
        R["cma"]["training"] = {"episodes": n, "sustained": sustained, "violated": viol, "missing": missing}

    # ---------------- Nominees ----------------
    geno = {}
    for name in ("cma-nominee", "random-nominee", "untrained"):
        p = root / "genotypes" / f"{name}.json"
        if p.exists():
            geno[name] = json.loads(p.read_text())
    if geno:
        R["genotypes"] = geno
        md += ["## Controllers evaluated", "", "| controller | " + " | ".join(FEATURES) + " | source |", "|---|" + "---:|" * 5 + "---|"]
        for name, g in geno.items():
            src = g["source"]
            extra = f"generator seed {src.get('generator_seed')}" + (f", training fitness {src['fitness']:.0f}" if "fitness" in src else "") if "generator_seed" in src else src.get("rule", src.get("kind"))
            md.append(f"| {name} | " + " | ".join(f"{v:+.2f}" for v in g["params"]) + f" | {extra} |")
        md.append("")
        md.append("A positive weight favours segments with a larger standardised value of that feature (the bonus is subtracted from the planner's cost).")
        md.append("")

    # ---------------- Random search ----------------
    search_path = root / "random" / "search.json"
    if search_path.exists():
        search = json.loads(search_path.read_text())
        R["random"] = {"nominee": search["nominee"], "draws": [{k: d[k] for k in ("generator_seed", "fitness")} for d in search["draws"]]}
        md += ["## Random search", "", f"16 draws on the eight generation 1 to 4 starts; nominee = generator seed {search['nominee']}.", "",
               "| generator seed | fitness | sustained | success | violated | missing |", "|---|---:|---:|---:|---:|---:|"]
        for d in sorted(search["draws"], key=lambda d: (-d["fitness"], d["generator_seed"])):
            tot = {k: sum(e[k] for e in d["episodes"]) for k in ("sustained", "success", "violated", "missing")}
            star = " (nominee)" if d["generator_seed"] == search["nominee"] else ""
            md.append(f"| {d['generator_seed']}{star} | {d['fitness']:.0f} | {tot['sustained']} | {tot['success']} | {tot['violated']} | {tot['missing']} |")
        md.append("")

    # ---------------- Evaluation panel ----------------
    ev = summaries(root, "eval")
    panel = cfg["evaluation_panel"]
    per = {arm: {} for arm in ARMS}
    for job, (att, s) in ev.items():
        _, arm, seed = job.split("-")
        per[arm][int(seed)] = outcome(att, s)
    present = [arm for arm in ARMS if per[arm]]
    if present:
        md += ["## Evaluation panel", "", f"{len(panel)} fresh starts ({panel[0]} to {panel[-1]}), paired by start. Wilson 95% intervals. No significance claim at n = 16.", "",
               "| controller | episodes | sustained safe success | success (any time) | violated | mean controls | failure kinds |", "|---|---:|---|---|---|---:|---|"]
        R["eval"] = {}
        for arm in present:
            o = per[arm]
            n = len(o)
            k_s, k_c, k_v = (sum(x[key] for x in o.values()) for key in ("sustained", "success", "violated"))
            kinds = {}
            for x in o.values():
                if x["violated"]:
                    kinds[x["kind"]] = kinds.get(x["kind"], 0) + 1
            mean_controls = sum(x["controls"] or 0 for x in o.values()) / n
            R["eval"][arm] = {"episodes": n, "sustained": k_s, "success": k_c, "violated": k_v, "sustained_ci": wilson(k_s, n), "violated_ci": wilson(k_v, n), "kinds": kinds, "mean_controls": mean_controls}
            md.append(f"| {LABEL[arm]} | {n} | {ci(k_s, n)} | {ci(k_c, n)} | {ci(k_v, n)} | {mean_controls:.0f} | {', '.join(f'{k} {v}' for k, v in sorted(kinds.items()))} |")
        md += ["", "Per start. S = sustained safe success; s = success not sustained; sV = success then violation; V = violation; . = neither (timeout).", "",
               "| start | " + " | ".join(LABEL[a] for a in present) + " |", "|---|" + "---|" * len(present)]
        for seed in panel:
            cells = [code(per[a][seed]) if seed in per[a] else "" for a in present]
            md.append(f"| {seed} | " + " | ".join(cells) + " |")
        md.append("")
        # Paired comparisons against native.
        if "native" in present:
            md += ["Discordant pairs against native (starts both controllers ran):", "", "| controller | sustained: gained / lost | violated: added / removed |", "|---|---|---|"]
            R["paired"] = {}
            for arm in present:
                if arm == "native":
                    continue
                both = [s for s in panel if s in per[arm] and s in per["native"]]
                g = sum(per[arm][s]["sustained"] and not per["native"][s]["sustained"] for s in both)
                l = sum(per["native"][s]["sustained"] and not per[arm][s]["sustained"] for s in both)
                a = sum(per[arm][s]["violated"] and not per["native"][s]["violated"] for s in both)
                r = sum(per["native"][s]["violated"] and not per[arm][s]["violated"] for s in both)
                R["paired"][arm] = {"starts": len(both), "sustained_gained": g, "sustained_lost": l, "violated_added": a, "violated_removed": r}
                md.append(f"| {LABEL[arm]} | {g} / {l} | {a} / {r} |")
            md.append("")
        # Verdict.
        if "native" in present and "cma" in present and len(per["cma"]) == len(panel) and len(per["native"]) == len(panel):
            ds = R["eval"]["cma"]["sustained"] - R["eval"]["native"]["sustained"]
            dv = R["eval"]["cma"]["violated"] - R["eval"]["native"]["violated"]
            if ds >= 3 and dv <= 0:
                verdict = "transfers"
            elif abs(ds) <= 1 and abs(dv) <= 1:
                verdict = "no signal"
            else:
                verdict = "mixed"
            tie = None
            if "random" in present and len(per["random"]) == len(panel):
                tie = abs(R["eval"]["cma"]["sustained"] - R["eval"]["random"]["sustained"]) <= 1
            R["verdict"] = {"rule": verdict, "d_sustained": ds, "d_violated": dv, "random_tie": tie}
            md += ["## Verdict by the pre-registered rules", "",
                   f"CMA minus native: sustained {ds:+d}, violated {dv:+d}. Rule outcome: **{verdict}**."
                   + ("" if tie is None else f" Random-search tie (|difference| <= 1 on sustained): **{tie}**."), ""]

    # ---------------- Cost ----------------
    cost = {}
    for phase in ("smoke", "cma", "random", "eval"):
        led = root / phase / "ledger.jsonl"
        if led.exists():
            entries = [json.loads(l) for l in led.read_text().splitlines() if l.strip()]
            ok = [e for e in entries if e.get("result")]
            cost[phase] = {"attempts": len(entries), "episodes": len(ok), "failed_attempts": len(entries) - len(ok),
                           "lane_seconds": sum(e["seconds"] for e in entries), "controls": sum((e["result"].get("controls") or e["result"].get("steps") or 0) for e in ok)}
    if cost:
        R["cost"] = cost
        md += ["## Cost", "", "| phase | episodes | failed attempts | lane-hours | simulator controls |", "|---|---:|---:|---:|---:|"]
        for phase, c in cost.items():
            md.append(f"| {phase} | {c['episodes']} | {c['failed_attempts']} | {c['lane_seconds'] / 3600:.2f} | {c['controls']} |")
        md.append("")

    args.output.write_text("\n".join(md) + "\n")
    (root / "pilot-results.json").write_text(json.dumps(R, indent=1, default=str) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
