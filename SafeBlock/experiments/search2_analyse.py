"""Analyse Search 2 records (protocol: SafeBlock/Search2.md) per repeat and pooled.

    python3 SafeBlock/experiments/search2_analyse.py            # repeats 0, 1, 2 if present

Reads SafeBlock/outputs/search2-20261102-r{N}/ and the matching configs; writes
SafeBlock/Search2Results-r{N}.md per repeat and SafeBlock/Search2Pooled.md. Partial
records give partial reports.
"""

import argparse
import json
from pathlib import Path

from pilot_analyse import ARMS, LABEL, code, outcome, summaries  # noqa: E402
from pilot_pool import mcnemar_exact  # noqa: E402
from search2 import FEATURES  # noqa: E402
from stage1_analyse import wilson  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def ci(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} [{lo:.2f}, {hi:.2f}]" if lo is not None else f"{k}/{n}"


def key_str(k):
    return f"({k[0]:.0f}, {k[1]:.0f}, {k[2]:.0f}, {k[3]:+.3f}, {k[4]:+.2f}, {k[5]:+.1f})"


def load_repeat(r):
    root, config = ROOT / f"SafeBlock/outputs/search2-20261102-r{r}", ROOT / f"SafeBlock/configs/search2-20261102-r{r}.json"
    if not root.exists() or not config.exists():
        return None
    cfg = json.loads(config.read_text())
    per = {arm: {} for arm in ARMS}
    for job, (att, s) in summaries(root, "final").items():
        _, arm, seed = job.split("-")
        per[arm][int(seed)] = outcome(att, s)
    x = {"repeat": r, "root": root, "cfg": cfg, "per": per, "panel": cfg["final_panel"], "genotypes": {}, "trace": None, "select": {}, "random": None, "parity": None}
    for name in ("cma-nominee", "cma-final-mean", "cma-elite", "random-nominee", "untrained"):
        p = root / "genotypes" / f"{name}.json"
        if p.exists():
            x["genotypes"][name] = json.loads(p.read_text())
    if (root / "cma" / "trace.json").exists():
        x["trace"] = json.loads((root / "cma" / "trace.json").read_text())
    for name in ("selectA", "selectB"):
        p = root / "select" / f"{name}.json"
        if p.exists():
            x["select"][name] = json.loads(p.read_text())
    if (root / "random" / "search.json").exists():
        x["random"] = json.loads((root / "random" / "search.json").read_text())
    if (root / "smoke" / "parity.json").exists():
        x["parity"] = json.loads((root / "smoke" / "parity.json").read_text())
    # Chosen-versus-base frozen features over the CMA nominee's final-panel episodes.
    diffs = []
    for job, (att, s) in summaries(root, "final").items():
        if "-cma-" in job and (att / "steps.jsonl").exists():
            for line in (att / "steps.jsonl").read_text().splitlines():
                row = json.loads(line)
                if row.get("adapter_changed_choice") and "adapter_features_chosen" in row:
                    diffs.append([c - b for c, b in zip(row["adapter_features_chosen"], row["adapter_features_base_choice"])])
    x["chosen_minus_base"] = [sum(d[j] for d in diffs) / len(diffs) for j in range(len(FEATURES))] if diffs else None
    x["changed_choices"] = len(diffs)
    return x


def repeat_report(x):
    cfg = x["cfg"]
    md = [f"# Search 2 results, repeat {x['repeat']}", "", f"Records: `SafeBlock/outputs/search2-20261102-r{x['repeat']}`. Protocol: [Search2.md](Search2.md). Generated by `experiments/search2_analyse.py`.", ""]
    if x["parity"]:
        md += ["## Parity smoke", "", f"Passed: **{x['parity']['passed']}**.", "", "| seed | controls | identical actions | identical cameras | identical shadow signals | same outcome | adapter changes |", "|---|---|---:|---:|---:|---|---:|"]
        for p in x["parity"]["pairs"]:
            if "error" in p:
                md.append(f"| {p['seed']} | {p['error']} | | | | | |")
            else:
                md.append(f"| {p['seed']} | {p['controls_reference']} / {p['controls_ours']} | {p['same_action']} | {p['same_camera']} | {p['same_shadow_signals']} | {p['same_outcome']} | {p['adapter_changes']} |")
        md.append("")
    if x["trace"]:
        gens = x["trace"]["generations"]
        md += ["## CMA-ES training trace", "", f"{len(gens)} of {cfg['cma']['generations']} generations; eight candidates x eight common starts each. Key = (sustained, success, -violated, -top excursion, progress, -completion time).", "",
               "| gen | best key | injected elite's rank | sustained / success / violated over 64 episodes | sigma after |", "|---:|---|---:|---|---:|"]
        for g in gens:
            tot = {k: sum(m[k] for name in g["measures"] for m in g["measures"][name]) for k in ("sustained", "success", "violated", "missing")}
            inj = g.get("injected_elite_index")
            inj_rank = g["ranks"][inj] if inj is not None else None
            md.append(f"| {g['generation']} | {key_str(g['elite_key'])} | {'' if inj_rank is None else inj_rank} | {tot['sustained']} / {tot['success']} / {tot['violated']}{' (missing ' + str(tot['missing']) + ')' if tot['missing'] else ''} | {g['sigma_after']:.3f} |")
        md.append("")
    if x["select"]:
        md += ["## Selection panel", "", f"{len(cfg['selection_panel'])} held-out starts per candidate.", "", "| phase | candidate | key | chosen |", "|---|---|---|---|"]
        for name, sel in x["select"].items():
            for cand, k in sel["keys"].items():
                md.append(f"| {name} | {cand} | {key_str(k)} | {'yes' if cand == sel['winner'] else ''} |")
        md.append("")
    if x["random"]:
        md += ["## Random search", "", f"64 draws; top two by key: {x['random']['top']}.", "", "| generator seed | block | key |", "|---|---:|---|"]
        for d in x["random"]["draws"][:8]:
            md.append(f"| {d['generator_seed']} | {d['block']} | {key_str(d['key'])} |")
        md += ["", "(top eight shown)", ""]
    if x["genotypes"]:
        md += ["## Controllers", "", "| controller | " + " | ".join(FEATURES) + " |", "|---|" + "---:|" * len(FEATURES)]
        for name, g in x["genotypes"].items():
            md.append(f"| {name} | " + " | ".join(f"{v:+.2f}" for v in g["params"]) + " |")
        md.append("")
    present = [arm for arm in ARMS if x["per"][arm]]
    if present:
        panel = x["panel"]
        md += ["## Final panel", "", f"{len(panel)} fresh starts, paired by start. Wilson 95% intervals.", "", "| controller | sustained safe success | success (any time) | violated | failure kinds |", "|---|---|---|---|---|"]
        for arm in present:
            o = x["per"][arm]
            n = len(o)
            k = {key: sum(v[key] for v in o.values()) for key in ("sustained", "success", "violated")}
            kinds = {}
            for v in o.values():
                if v["violated"]:
                    kinds[v["kind"]] = kinds.get(v["kind"], 0) + 1
            md.append(f"| {LABEL[arm]} | {ci(k['sustained'], n)} | {ci(k['success'], n)} | {ci(k['violated'], n)} | {', '.join(f'{a} {b}' for a, b in sorted(kinds.items()))} |")
        md += ["", "| start | " + " | ".join(LABEL[a] for a in present) + " |", "|---|" + "---|" * len(present)]
        for s in panel:
            md.append(f"| {s} | " + " | ".join(code(x["per"][a][s]) if s in x["per"][a] else "" for a in present) + " |")
        md.append("")
        if "native" in present and "cma" in present and len(x["per"]["cma"]) == len(panel) == len(x["per"]["native"]):
            ds = sum(v["sustained"] for v in x["per"]["cma"].values()) - sum(v["sustained"] for v in x["per"]["native"].values())
            dv = sum(v["violated"] for v in x["per"]["cma"].values()) - sum(v["violated"] for v in x["per"]["native"].values())
            verdict = "transfers" if (ds >= 3 and dv <= 0) else ("no signal" if (abs(ds) <= 1 and abs(dv) <= 1) else "mixed")
            md += ["## Verdict by the pre-registered rules", "", f"CMA minus native: sustained {ds:+d}, violated {dv:+d}. Outcome: **{verdict}**.", ""]
    if x["chosen_minus_base"]:
        md += ["## What the CMA nominee changed", "", f"Over {x['changed_choices']} changed choices on the final panel, mean (chosen minus planner's choice) per raw feature:", "",
               "| " + " | ".join(FEATURES) + " |", "|" + "---:|" * len(FEATURES), "| " + " | ".join(f"{v:+.3g}" for v in x["chosen_minus_base"]) + " |", ""]
    return md


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repeats", type=int, nargs="+", default=[0, 1, 2])
    args = parser.parse_args()
    reps = [x for x in (load_repeat(r) for r in args.repeats) if x is not None]
    for x in reps:
        (ROOT / f"SafeBlock/Search2Results-r{x['repeat']}.md").write_text("\n".join(repeat_report(x)) + "\n")
    CORE = ["native", "untrained", "cma"]
    complete = [x for x in reps if all(len(x["per"][arm]) == len(x["panel"]) for arm in CORE)]
    with_random = [x for x in complete if len(x["per"]["random"]) == len(x["panel"])]
    md = ["# Search 2 pooled", "", f"Protocol: [Search2.md](Search2.md). Repeats present {[x['repeat'] for x in reps]}, complete {[x['repeat'] for x in complete]}.", ""]
    md += ["## Per repeat", "", "| repeat | controller | sustained | success | violated |", "|---:|---|---|---|---|"]
    for x in reps:
        for arm in ARMS:
            o = x["per"][arm]
            if o:
                n = len(o)
                md.append(f"| {x['repeat']} | {LABEL[arm]} | {ci(sum(v['sustained'] for v in o.values()), n)} | {ci(sum(v['success'] for v in o.values()), n)} | {ci(sum(v['violated'] for v in o.values()), n)} |")
    md.append("")
    R = {"repeats": [x["repeat"] for x in reps], "complete": [x["repeat"] for x in complete]}
    if complete:
        md += ["## Pooled final panel", "", f"{16 * len(complete)} starts, paired by start (random-search arm complete in repeats {[x['repeat'] for x in with_random]} only).", "", "| controller | sustained | success | violated |", "|---|---|---|---|"]
        pooled = {}
        for arm in ARMS:
            source = with_random if arm == "random" else complete
            items = [x["per"][arm][s] for x in source for s in x["panel"]]
            n = len(items)
            if n == 0:
                continue
            pooled[arm] = {k: sum(v[k] for v in items) for k in ("sustained", "success", "violated")}
            pooled[arm]["n"] = n
            md.append(f"| {LABEL[arm]} | {ci(pooled[arm]['sustained'], n)} | {ci(pooled[arm]['success'], n)} | {ci(pooled[arm]['violated'], n)} |")
        md += ["", "| controller | sustained gained / lost | p | violated added / removed | p | per-repeat sustained difference |", "|---|---|---:|---|---:|---|"]
        for arm in ARMS:
            if arm == "native" or arm not in pooled:
                continue
            g = l = a = r_ = 0
            signs = []
            for x in (with_random if arm == "random" else complete):
                dg = sum(x["per"][arm][s]["sustained"] and not x["per"]["native"][s]["sustained"] for s in x["panel"])
                dl = sum(x["per"]["native"][s]["sustained"] and not x["per"][arm][s]["sustained"] for s in x["panel"])
                a += sum(x["per"][arm][s]["violated"] and not x["per"]["native"][s]["violated"] for s in x["panel"])
                r_ += sum(x["per"]["native"][s]["violated"] and not x["per"][arm][s]["violated"] for s in x["panel"])
                g += dg
                l += dl
                signs.append(dg - dl)
            fp = lambda p: "" if p is None else f"{p:.3f}"
            md.append(f"| {LABEL[arm]} | {g} / {l} | {fp(mcnemar_exact(g, l))} | {a} / {r_} | {fp(mcnemar_exact(a, r_))} | {', '.join(f'{d:+d}' for d in signs)} |")
        ds = pooled["cma"]["sustained"] - pooled["native"]["sustained"]
        dv = pooled["cma"]["violated"] - pooled["native"]["violated"]
        scale = len(complete) / 3
        verdict = "transfers" if (ds >= 9 * scale and dv <= 0) else ("no signal" if (abs(ds) <= 3 * scale and abs(dv) <= 3 * scale) else "mixed")
        tie = (abs(pooled["cma"]["sustained"] - pooled["random"]["sustained"]) <= 3 * scale) if "random" in pooled and len(with_random) == len(complete) else None
        R.update({"pooled": pooled, "verdict": verdict, "d_sustained": ds, "d_violated": dv, "random_tie": tie})
        md += ["", f"## Pooled verdict: **{verdict}** (CMA minus native: sustained {ds:+d}, violated {dv:+d}; random-search tie {tie})", ""]
    md += ["## Nominees and selection", "", "| repeat | nominee source | " + " | ".join(FEATURES) + " |", "|---:|---|" + "---:|" * len(FEATURES)]
    for x in reps:
        g = x["genotypes"].get("cma-nominee")
        if g:
            md.append(f"| {x['repeat']} | {g['source'].get('chosen')} | " + " | ".join(f"{v:+.2f}" for v in g["params"]) + " |")
    md.append("")
    (ROOT / "SafeBlock/Search2Pooled.md").write_text("\n".join(md) + "\n")
    (ROOT / "SafeBlock/outputs/search2-pooled.json").write_text(json.dumps(R, indent=1, default=str) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
