"""Pool the pilot repeats (protocol: SafeBlock/Pilot.md, "Repeats 1 and 2").

    python3 SafeBlock/experiments/pilot_pool.py            # repeats 0, 1, 2 if present

Reads SafeBlock/outputs/pilot-20261101[-rN]/ and the matching configs, writes
SafeBlock/PilotPooled.md and SafeBlock/outputs/pilot-20261101/pilot-pooled.json.
"""

import argparse
import json
import math
from pathlib import Path

from pilot_analyse import ARMS, FEATURES, LABEL, code, outcome, summaries  # noqa: E402
from stage1_analyse import wilson  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def mcnemar_exact(b, c):
    """Two-sided exact p for discordant counts b and c (binomial, p = 1/2)."""
    n = b + c
    if n == 0:
        return None
    k = min(b, c)
    p = sum(math.comb(n, i) for i in range(k + 1)) / 2**n
    return min(1.0, 2 * p)


def repeat_paths(r):
    suffix = "" if r == 0 else f"-r{r}"
    return ROOT / f"SafeBlock/outputs/pilot-20261101{suffix}", ROOT / f"SafeBlock/configs/pilot-20261101{suffix}.json"


def load_repeat(r):
    root, config = repeat_paths(r)
    if not root.exists() or not config.exists():
        return None
    cfg = json.loads(config.read_text())
    per = {arm: {} for arm in ARMS}
    for job, (att, s) in summaries(root, "eval").items():
        _, arm, seed = job.split("-")
        per[arm][int(seed)] = outcome(att, s)
    genotypes = {}
    for name in ("cma-nominee", "random-nominee", "untrained"):
        p = root / "genotypes" / f"{name}.json"
        if p.exists():
            genotypes[name] = json.loads(p.read_text())["params"]
    trace = root / "cma" / "trace.json"
    gens = json.loads(trace.read_text())["generations"] if trace.exists() else []
    return {"repeat": r, "root": root, "cfg": cfg, "per": per, "panel": cfg["evaluation_panel"], "genotypes": genotypes, "cma_best": [g["best"] for g in gens]}


def ci(k, n):
    lo, hi = wilson(k, n)
    return f"{k}/{n} [{lo:.2f}, {hi:.2f}]" if lo is not None else f"{k}/{n}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repeats", type=int, nargs="+", default=[0, 1, 2])
    parser.add_argument("--output", type=Path, default=ROOT / "SafeBlock/PilotPooled.md")
    args = parser.parse_args()
    reps = [x for x in (load_repeat(r) for r in args.repeats) if x is not None]
    complete = [x for x in reps if all(len(x["per"][arm]) == len(x["panel"]) for arm in ARMS)]
    md = ["# Pilot repeats pooled", "", f"Protocol: [Pilot.md](Pilot.md). Repeats present: {[x['repeat'] for x in reps]}; complete on all four arms: {[x['repeat'] for x in complete]}. "
          "Pooled rows use complete repeats only. Generated by `experiments/pilot_pool.py`.", ""]
    R = {"repeats_present": [x["repeat"] for x in reps], "repeats_complete": [x["repeat"] for x in complete]}

    md += ["## Per repeat", "", "| repeat | controller | sustained safe success | success (any time) | violated |", "|---:|---|---|---|---|"]
    R["per_repeat"] = {}
    for x in reps:
        R["per_repeat"][x["repeat"]] = {}
        for arm in ARMS:
            o = x["per"][arm]
            if not o:
                continue
            n = len(o)
            k = {key: sum(v[key] for v in o.values()) for key in ("sustained", "success", "violated")}
            R["per_repeat"][x["repeat"]][arm] = {"episodes": n, **k}
            md.append(f"| {x['repeat']} | {LABEL[arm]} | {ci(k['sustained'], n)} | {ci(k['success'], n)} | {ci(k['violated'], n)} |")
    md.append("")

    if complete:
        md += ["## Pooled panel", "", f"{sum(len(x['panel']) for x in complete)} starts across {len(complete)} repeats, paired by start. Wilson 95% intervals.", "",
               "| controller | sustained safe success | success (any time) | violated |", "|---|---|---|---|"]
        pooled = {}
        for arm in ARMS:
            items = [(x["repeat"], s, x["per"][arm][s]) for x in complete for s in x["panel"]]
            n = len(items)
            k = {key: sum(v[key] for _, _, v in items) for key in ("sustained", "success", "violated")}
            pooled[arm] = {"episodes": n, **k, "sustained_ci": wilson(k["sustained"], n), "violated_ci": wilson(k["violated"], n)}
            md.append(f"| {LABEL[arm]} | {ci(k['sustained'], n)} | {ci(k['success'], n)} | {ci(k['violated'], n)} |")
        R["pooled"] = pooled
        md += ["", "Paired against native over the pooled starts. McNemar's exact p is descriptive only.", "",
               "| controller | sustained: gained / lost | p | violated: added / removed | p | sustained difference per repeat |", "|---|---|---:|---|---:|---|"]
        R["paired"] = {}
        for arm in ARMS:
            if arm == "native":
                continue
            g = l = a = r_ = 0
            signs = []
            for x in complete:
                dg = dl = 0
                for s in x["panel"]:
                    mine, nat = x["per"][arm][s], x["per"]["native"][s]
                    dg += int(mine["sustained"] and not nat["sustained"])
                    dl += int(nat["sustained"] and not mine["sustained"])
                    a += int(mine["violated"] and not nat["violated"])
                    r_ += int(nat["violated"] and not mine["violated"])
                g += dg
                l += dl
                signs.append(dg - dl)
            ps, pv = mcnemar_exact(g, l), mcnemar_exact(a, r_)
            R["paired"][arm] = {"sustained_gained": g, "sustained_lost": l, "p_sustained": ps, "violated_added": a, "violated_removed": r_, "p_violated": pv, "sustained_difference_per_repeat": signs}
            fp = lambda p: "" if p is None else f"{p:.3f}"
            md.append(f"| {LABEL[arm]} | {g} / {l} | {fp(ps)} | {a} / {r_} | {fp(pv)} | {', '.join(f'{d:+d}' for d in signs)} |")
        md.append("")
        ds = pooled["cma"]["sustained"] - pooled["native"]["sustained"]
        dv = pooled["cma"]["violated"] - pooled["native"]["violated"]
        scale = len(complete) / 3  # thresholds pre-registered for three repeats (48 starts)
        t_transfer, t_null = 9 * scale, 3 * scale
        if ds >= t_transfer and dv <= 0:
            verdict = "transfers"
        elif abs(ds) <= t_null and abs(dv) <= t_null:
            verdict = "no signal"
        else:
            verdict = "mixed"
        tie = abs(pooled["cma"]["sustained"] - pooled["random"]["sustained"]) <= t_null
        same_sign = all(d > 0 for d in R["paired"]["cma"]["sustained_difference_per_repeat"]) or all(d < 0 for d in R["paired"]["cma"]["sustained_difference_per_repeat"])
        R["verdict"] = {"rule": verdict, "d_sustained": ds, "d_violated": dv, "thresholds": {"transfers": t_transfer, "no_signal": t_null}, "random_tie": tie, "same_sign_all_repeats": same_sign}
        md += ["## Pooled verdict by the pre-registered rules", "",
               f"CMA minus native over the pooled starts: sustained {ds:+d}, violated {dv:+d}. "
               f"Thresholds (scaled to {len(complete)} complete repeats): transfers at +{t_transfer:.0f} with no more violations, no signal within +-{t_null:.0f}. "
               f"Outcome: **{verdict}**. Random-search tie: **{tie}**. Same sign of the sustained difference in every repeat: **{same_sign}**.", ""]

    md += ["## Nominees", "", "| repeat | controller | " + " | ".join(FEATURES) + " |", "|---:|---|" + "---:|" * 5]
    R["genotypes"] = {}
    for x in reps:
        R["genotypes"][x["repeat"]] = x["genotypes"]
        for name, params in x["genotypes"].items():
            md.append(f"| {x['repeat']} | {name} | " + " | ".join(f"{v:+.2f}" for v in params) + " |")
    md += ["", "## CMA-ES best fitness per generation", "", "| repeat | " + " | ".join(f"g{i}" for i in range(1, 9)) + " |", "|---:|" + "---:|" * 8]
    for x in reps:
        md.append(f"| {x['repeat']} | " + " | ".join(f"{b:.0f}" for b in x["cma_best"]) + " |")
    md.append("")
    args.output.write_text("\n".join(md) + "\n")
    (ROOT / "SafeBlock/outputs/pilot-20261101/pilot-pooled.json").write_text(json.dumps(R, indent=1, default=str) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
